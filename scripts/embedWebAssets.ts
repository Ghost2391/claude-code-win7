import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { join, dirname } from 'node:path'

/**
 * Reads the static web assets from src/entrypoints/web/public and writes them
 * into a TS module (embeddedAssets.generated.ts) that gets bundled into the
 * compiled binary. This makes `--web` mode self-contained: the standalone
 * `claude` executable works even when `web/public` is not deployed next to it
 * (e.g. when the binary is installed to a system PATH on a Linux box).
 */
export async function generateEmbeddedWebAssets(root: string): Promise<void> {
  const publicDir = join(root, 'src', 'entrypoints', 'web', 'public')
  const mapping: Record<string, string> = {
    '/': 'index.html',
    '/index.html': 'index.html',
    '/favicon.svg': 'favicon.svg',
    '/xterm.min.js': 'xterm.min.js',
    '/xterm.min.css': 'xterm.min.css',
    '/xterm-addon-fit.min.js': 'xterm-addon-fit.min.js',
  }

  const assets: Record<string, string> = {}
  for (const [url, file] of Object.entries(mapping)) {
    assets[url] = await readFile(join(publicDir, file), 'utf-8')
  }

  const out = join(
    root,
    'src',
    'entrypoints',
    'web',
    'embeddedAssets.generated.ts',
  )
  const content =
    '// AUTO-GENERATED by build scripts (scripts/embedWebAssets.ts) — do not edit by hand.\n' +
    '// Empty map = assets resolved from the filesystem at runtime (dev / non-embedded builds).\n' +
    `export const EMBEDDED_WEB_ASSETS: Record<string, string> = ${JSON.stringify(assets)}\n`

  await mkdir(dirname(out), { recursive: true })
  await writeFile(out, content)
  console.log(
    `[embedWebAssets] Embedded ${Object.keys(assets).length} web assets → ${out}`,
  )
}
